def mc(q, a, b, c, d, correct, obj, diff, hint, expl, src="web"):
    """Build a CSV row for a multiple-choice question."""
    choices = [
        {"id": 1, "text": a, "order": 1},
        {"id": 2, "text": b, "order": 2},
        {"id": 3, "text": c, "order": 3},
        {"id": 4, "text": d, "order": 4},
    ]
    letter_map = {"A": 1, "B": 2, "C": 3, "D": 4}
    correct_id = letter_map[correct]
    return {
        "objective_code": obj,
        "question_text": q,
        "question_type": "multiple_choice",
        "difficulty": diff,
        "answer_choices_json": json.dumps(choices),
        "correct_answer_key_json": json.dumps({"correct_ids": [correct_id]}),
        "hint": hint,
        "explanation": expl,
        "source": src,
    }

