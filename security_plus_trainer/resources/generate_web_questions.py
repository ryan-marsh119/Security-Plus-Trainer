def open_csv_append(domain_key):
    path = DOMAIN_FILES[domain_key]
    f = open(path, "a", newline="", encoding="utf-8")
    writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
    return f, writer

def append_questions(questions):
    by_domain = {}
    for q in questions:
        domain = q["objective_code"].split(".")[0]
        by_domain.setdefault(domain, []).append(q)

    counts = {}
    for domain, rows in by_domain.items():
        if domain not in DOMAIN_FILES:
            print(f"  WARNING: no file for domain {domain}, skipping {len(rows)} questions")
            continue
        with open(csv_path := DOMAIN_FILES[domain], "a", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
            for row in rows:
                writer.writerow(row)
        counts[domain] = len(rows)

    return counts

def count_existing():
    totals = {}
    for domain, path in DOMAIN_FILES.items():
        with open(path, newline="", encoding="utf-8") as f:
            totals[domain] = sum(1 for _ in csv.DictReader(f))
    return totals

